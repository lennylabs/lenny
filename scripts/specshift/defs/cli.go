package defs

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/lennylabs/lenny/scripts/specshift/scope"
)

// Command is the specshift subcommand that runs this package.
const Command = "defs"

// usage is the subcommand's usage text.
const usage = `usage: specshift defs [-root <path>] <command>

commands:
  check               validate every definition block, anchor, page code, and generated-section marker
  generate [--check]  write the catalogs, the generated sections, and the folder indexes;
                      with --check, write nothing and fail when a generated file is stale
  schemas             print the definition-block schema reference in Markdown
`

// ErrProblems is returned when a check finds problems. The problems are
// written to the command's output before it returns.
var ErrProblems = errors.New("the specification tree has problems")

// ErrStale is returned by generate --check when a generated file differs
// from a fresh run. The stale files are written to the output first.
var ErrStale = errors.New("generated files are stale; run `" + GenerateCommand + "` and commit the result")

// Run runs the defs subcommand with the arguments that follow its name.
func Run(ctx context.Context, args []string, out io.Writer) error {
	fs := flag.NewFlagSet("specshift defs", flag.ContinueOnError)
	fs.SetOutput(out)
	fs.Usage = func() { fmt.Fprint(out, usage) }
	root := fs.String("root", "", "repo root (default: the git toplevel of the working directory)")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("parse flags: %w", err)
	}
	rest := fs.Args()
	if len(rest) == 0 {
		fs.Usage()
		return errors.New("a defs command is required: check, generate, or schemas")
	}
	if rest[0] == "schemas" {
		_, err := io.WriteString(out, SchemaDocument())
		return err
	}
	resolved, err := resolveRoot(ctx, *root)
	if err != nil {
		return err
	}
	switch rest[0] {
	case "check":
		return runCheck(resolved, rest[1:], out)
	case "generate":
		return runGenerate(resolved, rest[1:], out)
	}
	fs.Usage()
	return fmt.Errorf("unknown defs command %q", rest[0])
}

func resolveRoot(ctx context.Context, root string) (string, error) {
	if root != "" {
		return root, nil
	}
	cwd, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("resolve working directory: %w", err)
	}
	return scope.RepoRoot(ctx, cwd)
}

func runCheck(root string, args []string, out io.Writer) error {
	if len(args) > 0 {
		return fmt.Errorf("defs check takes no arguments, got %s", strings.Join(args, " "))
	}
	t, err := LoadTree(root)
	if err != nil {
		return err
	}
	problems := Check(t)
	if err := reportProblems(out, problems); err != nil {
		return err
	}
	fmt.Fprintf(out, "defs check: %d page(s), %d definition block(s), no problems\n", len(t.Pages), len(t.Blocks()))
	return nil
}

func reportProblems(out io.Writer, problems []Problem) error {
	if len(problems) == 0 {
		return nil
	}
	for _, p := range problems {
		fmt.Fprintln(out, p.String())
	}
	return fmt.Errorf("%w: %d problem(s)", ErrProblems, len(problems))
}

func runGenerate(root string, args []string, out io.Writer) error {
	fs := flag.NewFlagSet("specshift defs generate", flag.ContinueOnError)
	fs.SetOutput(out)
	checkOnly := fs.Bool("check", false, "write nothing; fail when a generated file differs from a fresh run")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("parse flags: %w", err)
	}
	if fs.NArg() > 0 {
		return fmt.Errorf("defs generate takes no arguments, got %s", strings.Join(fs.Args(), " "))
	}
	t, err := LoadTree(root)
	if err != nil {
		return err
	}
	generated, problems := Generate(t)
	if err := reportProblems(out, problems); err != nil {
		return err
	}
	if *checkOnly {
		stale, err := Stale(root, generated)
		if err != nil {
			return err
		}
		for _, p := range stale {
			fmt.Fprintf(out, "stale: %s\n", p)
		}
		if len(stale) > 0 {
			return fmt.Errorf("%w (%d file(s))", ErrStale, len(stale))
		}
		fmt.Fprintf(out, "defs generate --check: %d generated file(s) are current\n", len(generated))
		return nil
	}
	written, err := Write(root, generated)
	if err != nil {
		return err
	}
	for _, p := range written {
		fmt.Fprintf(out, "wrote %s\n", p)
	}
	fmt.Fprintf(out, "defs generate: %d generated file(s), %d written\n", len(generated), len(written))
	return nil
}

// SchemaDocument returns the text of SCHEMAS.md: a title, the generated
// header, and the schema reference.
func SchemaDocument() string {
	return "# Definition-block schemas\n\n" +
		"<!-- Generated by `go run ./scripts/specshift defs schemas`. Do not edit by hand. -->\n\n" +
		SchemaReference(2)
}
