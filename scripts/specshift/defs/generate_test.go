func TestGenerateCheckNamesAStaleFile(t *testing.T) {
	t.Parallel()
	root := copyTree(t, fixtureTree)
	var buf bytes.Buffer
	if err := Run(context.Background(), []string{"-root", root, "generate"}, &buf); err != nil {
		t.Fatalf("generate: %v\n%s", err, buf.String())
	}
	buf.Reset()
	if err := Run(context.Background(), []string{"-root", root, "generate", "--check"}, &buf); err != nil {
		t.Fatalf("generate --check on a fresh run: %v\n%s", err, buf.String())
	}
	target := filepath.Join(root, "spec/catalogs/metrics.md")
	content, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, append(content, "hand edit\n"...), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(root, "spec/catalogs/limits.md")); err != nil {
		t.Fatal(err)
	}
	buf.Reset()
	err = Run(context.Background(), []string{"-root", root, "generate", "--check"}, &buf)
	if !errors.Is(err, ErrStale) {
		t.Fatalf("generate --check over a stale tree returned %v, want ErrStale", err)
	}
	for _, want := range []string{"stale: spec/catalogs/metrics.md", "stale: spec/catalogs/limits.md"} {
		if !strings.Contains(buf.String(), want) {
			t.Errorf("output does not name %q:\n%s", want, buf.String())
		}
	}
	after, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasSuffix(after, []byte("hand edit\n")) {
		t.Errorf("generate --check wrote a file")
	}
}

func TestRunCheckReportsProblemsWithFileAndLine(t *testing.T) {
	t.Parallel()
	root := writeTree(t, baseFiles(blockPage("x", "kind: gadget\n")))
	var buf bytes.Buffer
	err := Run(context.Background(), []string{"-root", root, "check"}, &buf)
	if !errors.Is(err, ErrProblems) {
		t.Fatalf("check returned %v, want ErrProblems", err)
	}
	if !strings.Contains(buf.String(), "spec/caps/page.md:11: unknown kind \"gadget\"") {
		t.Errorf("output does not locate the problem:\n%s", buf.String())
	}
	buf.Reset()
	if err := Run(context.Background(), []string{"-root", copyTree(t, fixtureTree), "check"}, &buf); err != nil {
		t.Errorf("check over the fixture tree: %v\n%s", err, buf.String())
	}
}

func TestRunRefusesUnknownCommandsAndArguments(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	for _, args := range [][]string{
		{"-root", root},
		{"-root", root, "frobnicate"},
		{"-root", root, "check", "extra"},
		{"-root", root, "generate", "extra"},
		{"-root", root, "generate", "--nope"},
	} {
		var buf bytes.Buffer
		if err := Run(context.Background(), args, &buf); err == nil {
			t.Errorf("Run(%v) succeeded", args)
		}
	}
}

func TestSchemasDocumentIsCurrent(t *testing.T) {
	t.Parallel()
	var buf bytes.Buffer
	if err := Run(context.Background(), []string{"schemas"}, &buf); err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile("SCHEMAS.md", buf.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	committed, err := os.ReadFile("SCHEMAS.md")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(committed, buf.Bytes()) {
		t.Errorf("SCHEMAS.md is stale; run go run ./scripts/specshift defs schemas > scripts/specshift/defs/SCHEMAS.md")
	}
	for _, k := range Kinds() {
		if !strings.Contains(buf.String(), "## `"+k.Name+"`") {
			t.Errorf("the schema reference has no section for %s", k.Name)
		}
	}
}
