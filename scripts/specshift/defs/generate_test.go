func TestGeneratedFilesCarryAHeaderNamingTheCommand(t *testing.T) {
	t.Parallel()
	out := generateFixture(t, copyTree(t, fixtureTree))
	for p, content := range out {
		if path.Base(p) == IndexFile {
			if strings.Count(content, "<!-- generated:index -->") != 1 {
				t.Errorf("%s does not carry exactly one generated index section", p)
			}
			continue
		}
		if !strings.HasPrefix(p, CatalogDir+"/") {
			continue
		}
		lines := strings.Split(content, "\n")
		found := false
		for _, l := range lines[:min(len(lines), 12)] {
			if strings.Contains(l, "Generated by `"+GenerateCommand+"`") && strings.Contains(l, "Do not edit by hand") {
				found = true
			}
		}
		if !found {
			t.Errorf("%s has no generated header within its first 12 lines", p)
		}
	}
}

func TestGenerateIsDeterministicAndIdempotent(t *testing.T) {
	t.Parallel()
	root := copyTree(t, fixtureTree)
	first := generateFixture(t, root)
	again := generateFixture(t, root)
	for p := range first {
		if first[p] != again[p] {
			t.Errorf("two runs over one tree differ in %s", p)
		}
	}
	if _, err := Write(root, first); err != nil {
		t.Fatal(err)
	}
	second := generateFixture(t, root)
	stale, err := Stale(root, second)
	if err != nil {
		t.Fatal(err)
	}
	if len(stale) > 0 {
		t.Errorf("a run over generated output changed it: %v", stale)
	}
}

func TestGenerateKeepsTheFrontMatterAndTextOutsideTheSections(t *testing.T) {
	t.Parallel()
	out := generateFixture(t, copyTree(t, fixtureTree))
	k8s := out["spec/interfaces/kubernetes/index.md"]
	for _, s := range []string{"Hand-written conventions stay.", "## After the pages\n\nThis text stays too.", "code: K8S\n"} {
		if !strings.Contains(k8s, s) {
			t.Errorf("the Kubernetes index lost %q:\n%s", s, k8s)
		}
	}
	if strings.Count(out["spec/components/gateway/index.md"], "<!-- generated:index -->") != 1 {
		t.Errorf("the gateway index did not get exactly one appended index section:\n%s", out["spec/components/gateway/index.md"])
	}
	wpc := out["spec/components/warm-pool-controller.md"]
	if strings.Contains(wpc, "\nstale\n") || !strings.Contains(wpc, "Text after the sections stays.") {
		t.Errorf("the WarmPoolController page kept stale section text or lost text after it:\n%s", wpc)
	}
	caps := out["spec/capabilities/index.md"]
	if !strings.Contains(caps, "Stale text that the generator replaces.") || !strings.HasPrefix(caps, "---\ncode: CAPS\ntype: index\nsummary: >-\n  Lists the capability areas.\n---\n") {
		t.Errorf("the capabilities index lost its hand-written text or changed its front matter; an index page keeps every line outside its generated section:\n%s", caps)
	}
}

func TestGenerateKeepsTheCodeOfAnExistingCatalog(t *testing.T) {
	t.Parallel()
	root := copyTree(t, fixtureTree)
	existing := "---\ncode: CATSETTINGS\ntype: placeholder\nsummary: An older summary.\n---\n\nold body\n"
	if err := os.MkdirAll(filepath.Join(root, "spec/catalogs"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "spec/catalogs/settings.md"), []byte(existing), 0o644); err != nil {
		t.Fatal(err)
	}
	out := generateFixture(t, root)
	got := out["spec/catalogs/settings.md"]
	if !strings.HasPrefix(got, "---\ncode: CATSETTINGS\ntype: catalog\nsummary: Lists every setting") {
		t.Errorf("the settings catalog did not keep its code under the generated front matter:\n%s", got)
	}
	if strings.Contains(got, "old body") || strings.Contains(got, "An older summary") {
		t.Errorf("the settings catalog kept its old text:\n%s", got)
	}
}

func TestGenerateOverAnEmptyTreeWritesEmptyCatalogs(t *testing.T) {
	t.Parallel()
	root := writeTree(t, map[string]string{"spec/README.md": "# Root\n", "spec/01_numbered.md": "# 1. Numbered\n"})
	out := generateFixture(t, root)
	if len(out) != len(catalogs)+1 {
		t.Fatalf("generated %d files, want the %d catalogs and their index: %v", len(out), len(catalogs), sortedPaths(out))
	}
	for _, c := range catalogs {
		content := out[catalogPath(c.file)]
		if !strings.Contains(content, "it is empty because the specification holds none yet") {
			t.Errorf("%s does not say it is generated and empty:\n%s", c.file, content)
		}
	}
}

