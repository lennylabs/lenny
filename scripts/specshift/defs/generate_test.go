// These cases cover specification tooling rather than a platform behavior,
// so they carry no specification annotation. They pin the generators:
// each catalog, each generated section, and each folder index of a small
// tree against golden files, the determinism of a second run, and the
// --check mode's detection of a stale file.

var update = flag.Bool("update", false, "rewrite the golden files under testdata/golden")

const (
	fixtureTree   = "testdata/tree"
	fixtureGolden = "testdata/golden"
)

// copyTree copies a fixture directory into a fresh root.
func copyTree(t *testing.T, src string) string {
	t.Helper()
	root := t.TempDir()
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, p)
		if err != nil {
			return err
		}
		target := filepath.Join(root, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		content, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(target, content, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
	return root
}

func generateFixture(t *testing.T, root string) map[string]string {
	t.Helper()
	tr, err := LoadTree(root)
	if err != nil {
		t.Fatal(err)
	}
	out, problems := Generate(tr)
	if len(problems) > 0 {
		t.Fatalf("Generate refused the fixture tree:\n%s", joinProblems(problems))
	}
	return out
}

func TestGenerateMatchesTheGoldenFiles(t *testing.T) {
	root := copyTree(t, fixtureTree)
	out := generateFixture(t, root)
	if *update {
		if err := os.RemoveAll(fixtureGolden); err != nil {
			t.Fatal(err)
		}
		for p, content := range out {
			target := filepath.Join(fixtureGolden, filepath.FromSlash(p))
			if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(target, []byte(content), 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	golden := map[string]string{}
	err := filepath.WalkDir(fixtureGolden, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(fixtureGolden, p)
		if err != nil {
			return err
		}
		content, err := os.ReadFile(p)
		golden[filepath.ToSlash(rel)] = string(content)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	if got, want := sortedPaths(out), sortedPaths(golden); strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("generated files differ from the golden set\ngot:\n  %s\nwant:\n  %s", strings.Join(got, "\n  "), strings.Join(want, "\n  "))
	}
	for p, want := range golden {
		if out[p] != want {
			t.Errorf("%s differs from its golden file; run go test ./scripts/specshift/defs -run TestGenerateMatchesTheGoldenFiles -update and review the diff", p)
		}
	}
}

func sortedPaths(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for p := range m {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

