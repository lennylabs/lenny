func TestParseUnifiedDiffReadsTheNewSideOfEachHunk(t *testing.T) {
	t.Parallel()
	diff := "diff --git a/pkg/a.go b/pkg/a.go\n" +
		"--- a/pkg/a.go\n+++ b/pkg/a.go\n" +
		"@@ -3,0 +4,2 @@ func a() {\n+x\n+y\n" +
		"@@ -10 +12 @@\n-old\n+new\n" +
		"@@ -20,3 +23,0 @@\n-gone\n-gone\n-gone\n" +
		"diff --git a/pkg/b.go b/pkg/b.go\nnew file mode 100644\n" +
		"--- /dev/null\n+++ b/pkg/b.go\n@@ -0,0 +1 @@\n+package b\n"
	got, err := ParseUnifiedDiff(diff)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	want := map[string]map[int]bool{
		"pkg/a.go": {4: true, 5: true, 12: true},
		"pkg/b.go": {1: true},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("changed lines %v, want %v", got, want)
	}
	if _, err := ParseUnifiedDiff("+++ b/pkg/a.go\n@@ garbage @@\n"); err == nil {
		t.Error("an unreadable hunk header was accepted")
	}
}

// gitRepo creates a repository with one commit on the given branch.
func gitRepo(t *testing.T, branch string, files map[string]string) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skipf("not-yet-applicable: git is not on PATH, so no repository can be built: %v", err)
	}
	root := t.TempDir()
	run := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", append([]string{"-C", root, "-c", "user.name=alice", "-c", "user.email=alice@acme.com",
			"-c", "commit.gpgsign=false"}, args...)...)
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	run("init", "-q", "-b", branch)
	for p, body := range files {
		writeFile(t, root, p, body)
	}
	run("add", ".")
	run("commit", "-q", "-m", "base")
	return root
}

func writeFile(t *testing.T, root, p, body string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(p))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestLintBranchReadsOnlyTheLinesTheBranchChanges(t *testing.T) {
	t.Parallel()
	spec := string(readFixture(t, "lint", "spec.md"))
	placement := string(readFixture(t, "lint", "placement.go.txt"))
	root := gitRepo(t, "main", map[string]string{
		"spec/claims.md":          spec,
		"pkg/claim/claim.go":      placement,
		"pkg/claim/testdata/x.go": placement,
	})
	// The working tree changes one annotation inside a function body and
	// adds a generated file and a testdata file, which the lint leaves out.
	writeFile(t, root, "pkg/claim/claim.go", replaceLine(t, placement, 26, "\t\t// spec: CLAIM-R8"))
	writeFile(t, root, "pkg/claim/zz_generated.go", "// Code generated by fixture. DO NOT EDIT.\n\npackage claim\n\nfunc g() {\n\t// spec: CLAIM-R1\n}\n")
	writeFile(t, root, "pkg/claim/testdata/x.go", placement+"\n// spec: CLAIM-R2\nvar y = 1\n")

	rep, err := LintBranch(context.Background(), root)
	if err != nil {
		t.Fatalf("lint the branch: %v", err)
	}
	if rep.BaseRef != "main" || rep.Base == "" {
		t.Errorf("compared with %q at %q, want the merge base with main", rep.BaseRef, rep.Base)
	}
	if rep.Files != 1 {
		t.Errorf("read %d changed file(s), want claim.go alone", rep.Files)
	}
	if len(rep.Findings) != 1 || rep.Findings[0].Line != 26 || rep.Findings[0].Rule != InFunctionBody {
		t.Errorf("findings %v, want the changed annotation at line 26", rep.Findings)
	}
	if len(rep.Skipped) != 1 {
		t.Errorf("skipped %q, want the identifier check named as skipped for want of a registry", rep.Skipped)
	}
}

func TestLintBranchResolvesIdentifiersOnceTheRegistryExists(t *testing.T) {
	t.Parallel()
	root := gitRepo(t, "main", map[string]string{
		"spec/claims.md":     string(readFixture(t, "lint", "spec.md")),
		"spec/registry.json":       string(readFixture(t, "lint", "registry.json")),
		"issues/CLAIM/CLAIM-I4.md": "# CLAIM-I4\n",
		"pkg/claim/claim.go":       "package claim\n",
	})
	writeFile(t, root, "pkg/claim/claim.go", string(readFixture(t, "lint", "identifiers.go.txt")))
	rep, err := LintBranch(context.Background(), root)
	if err != nil {
		t.Fatalf("lint the branch: %v", err)
	}
	if len(rep.Skipped) != 0 {
		t.Errorf("skipped %q with a registry present", rep.Skipped)
	}
	if len(rep.Findings) != 4 {
		t.Errorf("findings %v, want the four unresolved identifiers", rep.Findings)
	}
}

