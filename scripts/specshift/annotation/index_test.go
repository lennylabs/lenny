// The annotation index is contributor tooling over the annotation rule
// of .claude/rules/spec-annotations.md rather than a behavior the
// specification states, so these cases carry no specification
// annotation.

// sign is the section sign, joined at run time so the citation gates do
// not read the fixtures below as citations of the repository's
// specification.
const sign = "§"

// memTree is an in-memory tree: a lister and a reader over a map.
type memTree map[string]string

func (m memTree) list(context.Context) ([]string, error) {
	var out []string
	for p := range m {
		out = append(out, p)
	}
	return out, nil
}

func (m memTree) read(p string) ([]byte, error) {
	s, ok := m[p]
	if !ok {
		return nil, fs.ErrNotExist
	}
	return []byte(s), nil
}

// indexFixture is a tree with annotations on a package doc comment, on
// code, and on test functions, a wrapped annotation, an unannotated test,
// a generated file, a testdata fixture, and a file that does not parse.
func indexFixture() memTree {
	return memTree{
		"pkg/pool/doc.go": "// Package pool claims pods.\n//\n// spec: POOL, CLAIM\npackage pool\n",
		"pkg/pool/claim.go": "package pool\n\n" +
			"// Claim picks a pod.\n//\n// spec: POOL-R5 (partial: POOL-I4)\nfunc Claim() {}\n\n" +
			"// Release frees a pod.\nfunc Release() {}\n",
		"pkg/pool/claim_test.go": "package pool\n\nimport \"testing\"\n\n" +
			"// TestClaimOrder checks the order.\n//\n// spec: POOL-R5, " + sign + "5.1 (Warm pools,\n// claims), 6.2 (Sizing)\nfunc TestClaimOrder(t *testing.T) {}\n\n" +
			"// TestReleaseFrees has no annotation.\nfunc TestReleaseFrees(t *testing.T) {}\n\n" +
			"func TestMain(m *testing.M) {}\n\nfunc Testable() {}\n\nfunc helper() {}\n\n" +
			"// spec: POOL-R6\nfunc (s suite) TestMethod(t *testing.T) {}\n",
		"pkg/pool/zz_generated.go":       "// Code generated by gen. DO NOT EDIT.\n\npackage pool\n\n// spec: POOL-R9\nfunc Gen() {}\n",
		"pkg/pool/testdata/fixture.go":   "package fixture\n\n// spec: POOL-R7\nfunc F() {}\n",
		"pkg/pool/broken_test.go":        "package pool\n\n// spec: POOL-R8\nfunc TestBroken(t *testing.T) {\n",
		"pkg/pool/README.md":             "spec: POOL-R1\n",
		"tests/component/pool/x_test.go": "package pool\n\nimport \"testing\"\n\n// spec: CLAIM-R1\nfunc TestX(t *testing.T) {}\n",
	}
}

func buildFixtureIndex(t *testing.T, tree memTree) *Index {
	t.Helper()
	x, err := BuildIndex(context.Background(), tree.list, tree.read)
	if err != nil {
		t.Fatalf("BuildIndex: %v", err)
	}
	return x
}

func TestIndexRecordsEachAnnotationWithItsSiteAndItems(t *testing.T) {
	t.Parallel()
	x := buildFixtureIndex(t, indexFixture())
	type row struct {
		Path, Decl, Kind string
		Func             bool
		IDs, Sections    []string
	}
	var got []row
	for _, c := range x.Citations {
		got = append(got, row{c.Path, c.Decl, c.Kind, c.Func, c.Identifiers, c.Sections})
	}
	want := []row{
		{"pkg/pool/broken_test.go", "", SiteTest, false, []string{"POOL-R8"}, nil},
		{"pkg/pool/claim.go", "Claim", SiteCode, true, []string{"POOL-R5", "POOL-I4"}, nil},
		{"pkg/pool/claim_test.go", "TestClaimOrder", SiteTest, true, []string{"POOL-R5"}, []string{"5.1", "6.2"}},
		{"pkg/pool/claim_test.go", "suite.TestMethod", SiteTest, true, []string{"POOL-R6"}, nil},
		{"pkg/pool/doc.go", "package pool", SitePackage, false, []string{"POOL", "CLAIM"}, nil},
		{"tests/component/pool/x_test.go", "TestX", SiteTest, true, []string{"CLAIM-R1"}, nil},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("citations:\n got %+v\nwant %+v", got, want)
	}
	if c := x.Citations[2]; c.Line != 7 || !strings.Contains(c.Payload, "claims), 6.2") {
		t.Fatalf("the wrapped annotation keeps its label line and joins its continuation: %+v", c)
	}
}

func TestIndexListsEveryTopLevelTestFunctionAnnotatedOrNot(t *testing.T) {
	t.Parallel()
	x := buildFixtureIndex(t, indexFixture())
	var got []string
	for _, tf := range x.Tests {
		got = append(got, tf.String())
	}
	want := []string{
		"pkg/pool/claim_test.go::TestClaimOrder",
		"pkg/pool/claim_test.go::TestReleaseFrees",
		"tests/component/pool/x_test.go::TestX",
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("tests:\n got %v\nwant %v", got, want)
	}
	order, ok := x.Test("pkg/pool", "TestClaimOrder")
	if !ok || len(order.Identifiers)+len(order.Sections) == 0 || order.Dir != "pkg/pool" || order.Line != 9 {
		t.Fatalf("TestClaimOrder: %+v, %v", order, ok)
	}
	if !reflect.DeepEqual(order.Identifiers, []string{"POOL-R5"}) || !reflect.DeepEqual(order.Sections, []string{"5.1", "6.2"}) {
		t.Fatalf("TestClaimOrder items: %v %v", order.Identifiers, order.Sections)
	}
	if free, _ := x.Test("pkg/pool", "TestReleaseFrees"); len(free.Identifiers)+len(free.Sections) > 0 {
		t.Fatalf("TestReleaseFrees carries no annotation: %+v", free)
	}
	if _, ok := x.Test("pkg/pool", "TestMissing"); ok {
		t.Fatal("a test the tree does not declare is not found")
	}
}

func TestIndexSitesCompareIdentifiersInLowerCase(t *testing.T) {
	t.Parallel()
	x := buildFixtureIndex(t, indexFixture())
	var got []string
	for _, s := range x.Sites("pool-r5") {
		got = append(got, s.String())
	}
	want := []string{"pkg/pool/claim.go:5 Claim", "pkg/pool/claim_test.go:7 TestClaimOrder"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Sites(pool-r5):\n got %v\nwant %v", got, want)
	}
	if s := x.Sites("POOL-R8"); len(s) != 1 || s[0].Decl != "" || s[0].String() != "pkg/pool/broken_test.go:3" {
		t.Fatalf("a file that does not parse keeps its annotation with no declaration: %+v", s)
	}
	for _, id := range []string{"POOL-R7", "POOL-R9", "POOL-R1", "POOL-R2"} {
		if s := x.Sites(id); len(s) != 0 {
			t.Errorf("Sites(%s) = %v; testdata, generated files, non-Go files, and absent identifiers yield none", id, s)
		}
	}
}

func TestIndexFilesKeepsOnlyTheFilesTheFilterAccepts(t *testing.T) {
	t.Parallel()
	tree := indexFixture()
	files := []string{"pkg/pool/claim.go", "pkg/pool/claim_test.go", "pkg/pool/doc.go"}
	keep := func(p string, _ []byte) bool { return p != "pkg/pool/claim_test.go" }
	x := IndexFiles(files, tree.read, keep)
	if len(x.Citations) != 2 || len(x.Tests) != 0 || len(x.Unread) != 0 {
		t.Fatalf("filtered index: %d citations, %d tests, unread %v", len(x.Citations), len(x.Tests), x.Unread)
	}
}

func TestIndexFilesReportsAnUnreadableFileAndReadsTheRest(t *testing.T) {
	t.Parallel()
	tree := indexFixture()
	x := IndexFiles([]string{"pkg/pool/absent.go", "pkg/pool/claim.go"}, tree.read, nil)
	if len(x.Unread) != 1 || !strings.HasPrefix(x.Unread[0], "pkg/pool/absent.go: ") {
		t.Fatalf("unread: %v", x.Unread)
	}
	if len(x.Citations) != 1 || x.Citations[0].Path != "pkg/pool/claim.go" {
		t.Fatalf("the readable file is indexed: %+v", x.Citations)
	}
}

func TestCheckedReaderRefusesASymbolicLink(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	outside := t.TempDir()
	write := func(p, body string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(filepath.Join(root, "pkg", "a", "a.go"), "package a\n\n// spec: POOL-R5\nfunc A() {}\n")
	write(filepath.Join(outside, "secret.go"), "package b\n\n// spec: POOL-R6\nfunc B() {}\n")
	if err := os.Symlink(filepath.Join(outside, "secret.go"), filepath.Join(root, "pkg", "a", "link.go")); err != nil {
		t.Skipf("blocked: the host does not allow a symbolic link: %v", err)
	}
	x := IndexFiles([]string{"pkg/a/a.go", "pkg/a/link.go", "pkg/a/gone.go"}, CheckedReader(root), nil)
	if len(x.Citations) != 1 || x.Citations[0].Path != "pkg/a/a.go" {
		t.Fatalf("only the regular file is indexed: %+v", x.Citations)
	}
	if len(x.Unread) != 2 || !strings.Contains(x.Unread[0], "symbolic link") || !strings.HasPrefix(x.Unread[1], "pkg/a/gone.go: ") {
		t.Fatalf("unread: %v", x.Unread)
	}
}

func TestIsGeneratedReadsTheHeaderOnlyBeforeThePackageClause(t *testing.T) {
	t.Parallel()
	header := "// Code generated by gen. DO NOT EDIT."
	cases := map[string]bool{
		header + "\n\npackage x\n":                            true,
		"//go:build linux\n\n" + header + "\n\npackage x\n":   true,
		"/* licence\n   text */\n" + header + "\npackage x\n": true,
		"// Package x.\npackage x\n\n" + header + "\n":        false,
		"package gen\n\nconst h = `\n" + header + "\n`\n":     false,
		"package x\n": false,
		"// Code generated by gen. DO NOT EDIT\n\npackage x\n": false,
		"/* one-line block */\n" + header + "\npackage x\n":    true,
		"": false,
	}
	for src, want := range cases {
		if got := IsGenerated([]byte(src)); got != want {
			t.Errorf("IsGenerated(%q) = %v, want %v", src, got, want)
		}
	}
}

