func TestSectionNumbersReadEachFormOnce(t *testing.T) {
	t.Parallel()
	cases := map[string][]string{
		sign + "4.7 (Pod claims, release)":                  {"4.7"},
		"4.7 (bare form), 11.7":                             {"4.7", "11.7"},
		sign + "4.7 / " + sign + "5.1":                      {"4.7", "5.1"},
		sign + "4.7 (see " + sign + "9.1), " + sign + "4.7": {"4.7"},
		"POOL-R5, " + sign + " 12.3.":                       {"12.3"},
		"POOL-R5":                                           nil,
		"":                                                  nil,
	}
	for payload, want := range cases {
		if got := SectionNumbers(payload); !reflect.DeepEqual(got, want) {
			t.Errorf("SectionNumbers(%q) = %v, want %v", payload, got, want)
		}
	}
}

