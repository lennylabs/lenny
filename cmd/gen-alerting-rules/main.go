type artifact struct {
	relPath string
	content []byte
}

func main() {
	out := flag.String("o", "", "chart-fragment output path (default: "+chartFragmentPath+" under the repo root)")
	check := flag.Bool("check", false, "verify every committed artefact is current; exit non-zero if any is stale")
	flag.Parse()

	chartFragment, err := renderChartFragment()
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-alerting-rules: %v\n", err)
		os.Exit(1)
	}

	root, err := repoRoot()
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-alerting-rules: %v\n", err)
		os.Exit(1)
	}

	chartPath := *out
	if chartPath == "" {
		chartPath = filepath.Join(root, chartFragmentPath)
	}

	docsRules, err := renderDocsRules()
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-alerting-rules: %v\n", err)
		os.Exit(1)
	}

	openSLOFragment, err := renderOpenSLOFragment()
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-alerting-rules: %v\n", err)
		os.Exit(1)
	}

	docsOpenSLO, err := renderDocsOpenSLO()
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-alerting-rules: %v\n", err)
		os.Exit(1)
	}

	artefacts := []artifact{
		{relPath: chartPath, content: chartFragment},
		{relPath: filepath.Join(root, docsRulesPath), content: docsRules},
		{relPath: filepath.Join(root, docsRoutingPath), content: []byte(routingDoc)},
		{relPath: filepath.Join(root, openSLOFragmentPath), content: openSLOFragment},
		{relPath: filepath.Join(root, docsOpenSLOPath), content: docsOpenSLO},
	}

	if *check {
		stale := false
		for _, a := range artefacts {
			existing, err := os.ReadFile(a.relPath)
			if err != nil {
				fmt.Fprintf(os.Stderr, "gen-alerting-rules: -check: %v\n", err)
				stale = true
				continue
			}
			if !bytes.Equal(existing, a.content) {
				fmt.Fprintf(os.Stderr, "gen-alerting-rules: %s is stale; run `make generate`\n", a.relPath)
				stale = true
			}
		}
		if stale {
			os.Exit(1)
		}
		return
	}

	for _, a := range artefacts {
		if err := os.MkdirAll(filepath.Dir(a.relPath), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "gen-alerting-rules: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(a.relPath, a.content, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "gen-alerting-rules: %v\n", err)
			os.Exit(1)
		}
	}
	fmt.Printf("gen-alerting-rules: rendered %d rules and %d SLOs → %s, %s, %s, %s, %s\n",
		len(rules.Catalog()), len(rules.SLODefinitions()),
		chartPath, docsRulesPath, docsRoutingPath, openSLOFragmentPath, docsOpenSLOPath)
}

// renderChartFragment builds the header-prefixed spec.groups fragment
// the Helm chart splices into the PrometheusRule CRD and the ConfigMap
// rule-file data section.
func renderChartFragment() ([]byte, error) {
	groups, err := rules.RenderRuleGroupsBySeverity(ruleGroupPrefix, rules.Catalog())
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(chartHeader)
	buf.Write(groups)
	return buf.Bytes(), nil
}

// renderDocsRules builds the docs/alerting/rules.yaml reference. The
// content is identical to the chart fragment but carries a docs-facing
// header pointing operators at the translation use case.
func renderDocsRules() ([]byte, error) {
	groups, err := rules.RenderRuleGroupsBySeverity(ruleGroupPrefix, rules.Catalog())
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(docsRulesHeader)
	buf.Write(groups)
	return buf.Bytes(), nil
}

// renderOpenSLOFragment builds the §16.10 OpenSLO export the chart
// bundles. It carries the tier placeholder so the chart can substitute
// global.deploymentTier at install time.
func renderOpenSLOFragment() ([]byte, error) {
	docs, err := rules.RenderOpenSLO(rules.OpenSLOService, rules.SLOTierPlaceholder, rules.SLONotificationTargetPlaceholder)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(openSLOChartHeader)
	buf.Write(docs)
	return buf.Bytes(), nil
}

// renderDocsOpenSLO builds the operator-facing OpenSLO reference with a
// concrete tier1 example so deployers translating to an OpenSLO tool see
// resolved queries rather than the chart's substitution placeholder.
func renderDocsOpenSLO() ([]byte, error) {
	docs, err := rules.RenderOpenSLO(rules.OpenSLOService, "tier1", rules.OpenSLODefaultNotificationTarget)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(openSLODocsHeader)
	buf.Write(docs)
	return buf.Bytes(), nil
}

// repoRoot walks up from the working directory to the module root.
func repoRoot() (string, error) {
	wd, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for d := wd; ; {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return d, nil
		}
		parent := filepath.Dir(d)
		if parent == d {
			return "", fmt.Errorf("no go.mod found above %s", wd)
		}
		d = parent
	}
}
