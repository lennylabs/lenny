// Command gen-alerting-rules renders the §16.5 alert catalog from the
// shared pkg/alerting/rules package into the YAML fragment the Helm
// chart bundles and into the docs/alerting/ reference set.
//
// §16.9 and §25.13 require the chart's PrometheusRule to be generated
// from the single pkg/alerting/rules source so the rendered manifest
// cannot drift from the gateway's in-process alert evaluator. The
// generator is that build step. §25.13 line 4720 also requires the
// catalog to be rendered into docs/alerting/rules.yaml for deployers
// using non-Prometheus stacks (Datadog, Grafana Cloud, Victoria
// Metrics, etc.), and §25.13 line 4804 requires a severity → routing
// recommendation page in docs/alerting/routing-recommendations.md.
//
// Usage:
//
//	gen-alerting-rules                Write all generated artefacts.
//	gen-alerting-rules -o <path>      Write the chart fragment only,
//	                                  to the supplied path.
//	gen-alerting-rules -check         Exit non-zero if any committed
//	                                  artefact is stale (no write).
//
// The Makefile `generate` target runs it; the alerting-rules
// cross-check test runs it with -check so a stale fragment fails CI.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/lennylabs/lenny/pkg/alerting/rules"
)

// ruleGroupPrefix is the PrometheusRule group-name prefix. The
// generator splits the catalog into one rule group per §16.5 severity
// ("lenny.critical", "lenny.warning", "lenny.info") so Prometheus can
// evaluate the buckets in parallel rather than serialising the full
// catalog through a single group; see §25.13 line 4822 per-group
// evaluation cost. F-25.13.9.
const ruleGroupPrefix = "lenny"

// chartFragmentPath is the chart-relative path of the bundled fragment.
const chartFragmentPath = "charts/lenny/files/alerting-rules.yaml"

// openSLOFragmentPath is the chart-relative path of the §16.10 OpenSLO
// export fragment. The chart's openslo-configmap.yaml template splices
// it into a ConfigMap, substituting global.deploymentTier for the
// SLOTierPlaceholder the fragment carries.
const openSLOFragmentPath = "charts/lenny/files/openslo.yaml"

// docsOpenSLOPath is the operator-facing OpenSLO reference, rendered
// with a concrete tier1 example tier so deployers translating to an
// OpenSLO tool have a readable starting point (§16.10).
const docsOpenSLOPath = "docs/alerting/openslo.yaml"

// docsRulesPath is the §25.13 line 4720 docs reference: the full rule
// set rendered for deployers translating to non-Prometheus stacks.
const docsRulesPath = "docs/alerting/rules.yaml"

// docsRoutingPath is the §25.13 line 4804 severity → routing
// recommendations page.
const docsRoutingPath = "docs/alerting/routing-recommendations.md"

