// The coverage floor's handling of files the profile does not hold, and
// the checks on `gate --cover`, are contributor tooling (change 0172,
// decisions 8 and 9), so these cases carry no specification annotation.

// TestCoverageDiffCountsAChangedFileTheProfileDoesNotHold checks that a
// changed production file the profile does not hold adds its changed code
// lines in function bodies as uncovered, so an empty profile fails the
// floor for untested code, while a test file, a generated file, a file of
// a tier's test directory, and changed lines outside function bodies add
// nothing.
func TestCoverageDiffCountsAChangedFileTheProfileDoesNotHold(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	src := "package x\n\nimport \"fmt\"\n\n// F prints.\nfunc F() {\n\t// a comment\n\n\tfmt.Println(1)\n\tg := func() {\n\t\tfmt.Println(2)\n\t}\n\tg()\n}\n"
	write("pkg/x/x.go", src)
	write("pkg/x/x_test.go", src)
	write("pkg/x/gen.go", "// Code generated by hand. DO NOT EDIT.\n\n"+src)
	write("tests/component/x/helper.go", src)
	all := []lineRange{{1, 14}}
	// Lines 9 to 13 hold code inside F's body; 7 is a comment, 8 is
	// blank, and 1 to 6 and 14 lie outside the body.
	if got := unmeasuredStatementLines(root, "pkg/x/x.go", all); got != 5 {
		t.Errorf("unmeasured lines of a production file = %d; want 5", got)
	}
	if got := unmeasuredStatementLines(root, "pkg/x/x.go", []lineRange{{1, 6}, {7, 8}}); got != 0 {
		t.Errorf("changed lines outside the body or without code = %d; want 0", got)
	}
	for _, file := range []string{"pkg/x/x_test.go", "pkg/x/gen.go", "tests/component/x/helper.go", "pkg/x/gone.go"} {
		if got := unmeasuredStatementLines(root, file, all); got != 0 {
			t.Errorf("%s adds %d lines; want 0", file, got)
		}
	}
	write("pkg/x/broken.go", "package x\nfunc {")
	if got := unmeasuredStatementLines(root, "pkg/x/broken.go", all); got != 0 {
		t.Errorf("a file that does not parse adds %d lines", got)
	}
	if !diffCoverageBelow(0.80, 0, 5) {
		t.Error("5 uncovered lines pass the floor")
	}
}

// TestGateCoverProfileErrorRefusesAProfileTheGateDoesNotWrite checks that
// --cover refuses LENNY_COVER_PROFILE set empty anywhere, and set to
// another path on the host half, whose container writes the default path.
func TestGateCoverProfileErrorRefusesAProfileTheGateDoesNotWrite(t *testing.T) {
	root := "/w"
	env := func(v string, ok bool) func(string) (string, bool) {
		return func(string) (string, bool) { return v, ok }
	}
	if err := gateCoverProfileError(false, root, env("", false)); err != nil {
		t.Errorf("unset: %v", err)
	}
	if err := gateCoverProfileError(false, root, env("/w/tests/results/cover.out", true)); err != nil {
		t.Errorf("the default path: %v", err)
	}
	if err := gateCoverProfileError(true, root, env("/elsewhere/cover.out", true)); err != nil {
		t.Errorf("--here with another path: %v", err)
	}
	if err := gateCoverProfileError(false, root, env("/elsewhere/cover.out", true)); err == nil {
		t.Error("the host half accepted a profile path the container does not write")
	}
	if err := gateCoverProfileError(true, root, env("", true)); err == nil {
		t.Error("--cover accepted LENNY_COVER_PROFILE set empty")
	}
}

// TestGateCoverWritesAnEmptyProfileWhenTheUnitTierWroteNone checks that a
// --cover run whose unit tier ran only test functions by name, which
// writes no profile, ends with a profile that covers nothing.
func TestGateCoverWritesAnEmptyProfileWhenTheUnitTierWroteNone(t *testing.T) {
	root := t.TempDir()
	profile := filepath.Join(root, "cover.out")
	g := laneRunner(&laneLog{}, nil, nil)
	g.plan = func(string, int, bool) (resolvedSelector, error) {
		return resolvedSelector{tiers: []tierPlan{{name: tierUnit, pkgs: []string{}, funcs: map[string][]string{"./pkg/a": {"TestA"}}, noCoverage: true}}}, nil
	}
	v := g.run(gateOptions{root: root, base: "main", rdepsDepth: defaultRdepsDepth, cover: true, coverProfile: profile, environment: "lenny-gate:test"})
	if body, _ := os.ReadFile(profile); string(body) != "mode: atomic\n" || v.Gate.CoverProfile != "cover.out" {
		t.Errorf("profile %q recorded %q; want one that covers nothing", body, v.Gate.CoverProfile)
	}
}

// TestGateHistoryLineNamesWhatTheRunRan checks that the run history
// records a gate run's commit, --all, the restriction, and --cover, so a
// restricted run reads apart from a run of every tier.
func TestGateHistoryLineNamesWhatTheRunRan(t *testing.T) {
	dir := t.TempDir()
	g := laneRunner(&laneLog{}, nil, nil)
	v := g.run(gateOptions{root: dir, base: "main", rdepsDepth: defaultRdepsDepth, tiers: []string{tierStatic, tierUnit}, environment: "lenny-gate:test"})
	v.finalize()
	hist := filepath.Join(dir, "history.jsonl")
	if err := appendHistory(hist, v); err != nil {
		t.Fatal(err)
	}
	body, _ := os.ReadFile(hist)
	for _, want := range []string{`"git_revision":"abc123"`, `"all":false`, `"restricted_to":["static","unit"]`} {
		if !strings.Contains(string(body), want) {
			t.Errorf("history line lacks %s: %s", want, body)
		}
	}
	if strings.Contains(string(body), `"cover"`) {
		t.Errorf("a run without --cover records cover: %s", body)
	}
}
