// The source scan of the static tier's golangci-lint check. It reads every
// tracked or untracked Go file outside testdata directories and refuses
// the constructs that hide code from both golangci-lint runs without a
// finding: a //nolint directive that lists `all`, a build tag the runs do
// not set, and a negated build tag the runs do set. It runs on every
// branch, because it is part of the static tier rather than a unit test
// of lenny-test that the merge gate selects only when lenny-test changes.
// The check is contributor tooling, so this file carries no
// specification annotation.

// nolintAllDirective matches the linter list of a //nolint directive in
// the text of one comment, with its leading slashes and spaces removed,
// as golangci-lint reads a directive.
var nolintAllDirective = regexp.MustCompile(`^nolint:([\w-]+(?:,[\w-]+)*)`)

// lintBuildTagExempt holds the build constraint names a Go file may carry
// that the lint does not set: the operating systems and architectures,
// which the target build decides, and the tags that mark files no build
// compiles.
var lintBuildTagExempt = map[string]bool{
	"linux": true, "unix": true, "darwin": true, "windows": true, "amd64": true, "arm64": true,
	"cgo": true, "ignore": true, "ignore_autogenerated": true,
}

// lintScanSkipped reports whether the scan leaves a path out: testdata
// directories, whose fixtures no build compiles, and the change and
// proposal records, which keep evidence files as they were written.
func lintScanSkipped(p string) bool {
	return strings.Contains("/"+p, "/testdata/") || strings.HasPrefix(p, "changes/") || strings.HasPrefix(p, "proposals/")
}

// scanLintSources returns each problem the scan finds in the Go files of
// root, sorted, as `<path>:<line>: <problem>`.
func scanLintSources(ctx context.Context, root string) ([]string, error) {
	out, err := gitOutput(ctx, root, "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "*.go")
	if err != nil {
		return nil, err
	}
	tags := map[string]bool{}
	for _, tag := range lintBuildTags() {
		tags[tag] = true
	}
	var found []string
	for _, p := range splitNUL(out) {
		if lintScanSkipped(p) {
			continue
		}
		body, err := os.ReadFile(filepath.Join(root, p))
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				continue
			}
			return nil, fmt.Errorf("read %s: %w", p, err)
		}
		found = append(found, nolintAllLines(p, body)...)
		found = append(found, buildTagProblems(p, body, tags)...)
	}
	sort.Strings(found)
	return found, nil
}

// nolintAllLines returns a problem for each comment of the Go source body
// that is a //nolint directive listing `all`. nolintlint reads a list as
// specific unless it starts with `all`, and golangci-lint widens an `all`
// anywhere in the list to every linter, so a directive such as
// `//nolint:gosec,all // reason` passes require-specific and silences
// every linter on its line or declaration. The function reads the
// comments the parser returns, so a mention of a directive inside another
// comment or a string is not a directive, and it reads what a file that
// does not parse in full still yields.
func nolintAllLines(p string, body []byte) []string {
	fset := token.NewFileSet()
	f, _ := parser.ParseFile(fset, p, body, parser.ParseComments)
	if f == nil {
		return nil
	}
	var found []string
	for _, group := range f.Comments {
		for _, c := range group.List {
			m := nolintAllDirective.FindStringSubmatch(strings.TrimLeft(c.Text, "/ \t"))
			if m == nil {
				continue
			}
			for _, item := range strings.Split(m[1], ",") {
				if item == "all" {
					found = append(found, fmt.Sprintf("%s:%d: a //nolint directive lists all, which silences every linter; name the linter", p, fset.Position(c.Pos()).Line))
					break
				}
			}
		}
	}
	return found
}

// buildTagProblems returns a problem for each build tag in the file's
// //go:build lines that the lint runs do not set and that
// lintBuildTagExempt does not hold, and for each lint tag the constraint
// negates. A file behind a tag the runs do not set, or behind the
// negation of one they do set, is compiled into some build and read by
// neither run. Only the lines before the package clause are read, as the
// go command reads them, so a constraint quoted in a string is not one.
func buildTagProblems(p string, body []byte, tags map[string]bool) []string {
	var found []string
	sc := bufio.NewScanner(bytes.NewReader(body))
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for n := 1; sc.Scan(); n++ {
		line := sc.Text()
		if strings.HasPrefix(line, "package ") {
			break
		}
		if !constraint.IsGoBuild(line) {
			continue
		}
		expr, err := constraint.Parse(line)
		if err != nil {
			found = append(found, fmt.Sprintf("%s:%d: the build constraint does not parse: %v", p, n, err))
			continue
		}
		for _, t := range constraintTags(expr, false) {
			switch {
			case t.negated && tags[t.tag]:
				found = append(found, fmt.Sprintf("%s:%d: the build constraint negates %s, which the lint sets, so neither lint run reads the file", p, n, t.tag))
			case !tags[t.tag] && !lintBuildTagExempt[t.tag]:
				found = append(found, fmt.Sprintf("%s:%d: build tag %s is not one the lint sets (lintBuildTags)", p, n, t.tag))
			}
		}
	}
	return found
}

// constraintTag is one tag a build constraint names, and whether an odd
// number of negations encloses it.
type constraintTag struct {
	tag     string
	negated bool
}

// constraintTags returns every tag a build constraint names, on both
// sides of each operator, with whether it is negated.
func constraintTags(e constraint.Expr, negated bool) []constraintTag {
	switch x := e.(type) {
	case *constraint.TagExpr:
		return []constraintTag{{tag: x.Tag, negated: negated}}
	case *constraint.NotExpr:
		return constraintTags(x.X, !negated)
	case *constraint.AndExpr:
		return append(constraintTags(x.X, negated), constraintTags(x.Y, negated)...)
	case *constraint.OrExpr:
		return append(constraintTags(x.X, negated), constraintTags(x.Y, negated)...)
	}
	return nil
}

// sourceSection runs the source scan and fails the check on any problem
// it finds, or when it cannot read the tree.
func (l golangciLint) sourceSection(ctx context.Context) (string, error) {
	found, err := l.scan(ctx, l.root)
	if err != nil {
		return fmt.Sprintf("the source scan of the golangci-lint check did not finish: %v", err), fmt.Errorf("source scan: %w", err)
	}
	if len(found) > 0 {
		return fmt.Sprintf("Go sources that hide code from golangci-lint:\n  %s", strings.Join(found, "\n  ")),
			fmt.Errorf("source scan: %d problem(s)", len(found))
	}
	return "source scan: no //nolint directive lists all, and every build tag is one the lint sets", nil
}
